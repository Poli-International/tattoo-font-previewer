export const DICTIONARIES: Record<SupportedLanguage, Record<string, string>> = {
    en: DICTIONARY,
    de: DICTIONARY_DE,
    es: DICTIONARY_ES,
    fr: DICTIONARY_FR,
    it: DICTIONARY_IT,
    pt: DICTIONARY_PT,
    nl: DICTIONARY_NL
};

let currentLanguage: SupportedLanguage = 'en';

export const setLanguage = (lang: SupportedLanguage) => {
    currentLanguage = lang;
    // Screen readers and the browser's own translate prompt read <html lang>.
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
    // The tab bar and the docs frame live outside React, so they follow the switch here.
    translateDom(lang);
    try {
        localStorage.setItem('poli-lang', lang);
    } catch {
        // LocalStorage fallback
    }
};

export const getLanguage = (): SupportedLanguage => currentLanguage;

export const getInitialLanguage = (): SupportedLanguage => {
    try {
        const stored = localStorage.getItem('poli-lang');
        if (stored && ['en', 'de', 'es', 'fr', 'it', 'pt', 'nl'].includes(stored)) {
            currentLanguage = stored as SupportedLanguage;
            if (typeof document !== 'undefined') document.documentElement.lang = stored;
            return currentLanguage;
        }
        if (typeof navigator !== 'undefined' && navigator.language) {
            const browser = navigator.language.slice(0, 2);
            if (['en', 'de', 'es', 'fr', 'it', 'pt', 'nl'].includes(browser)) {
                currentLanguage = browser as SupportedLanguage;
                return currentLanguage;
            }
        }
    } catch {
        // Fallback
    }
    return 'en';
};

export const t = (key: string, lang?: SupportedLanguage, params?: Record<string, string | number>): string => {
    const activeLang = lang || currentLanguage;
    const dict = DICTIONARIES[activeLang] || DICTIONARY;
    let text = dict[key] || DICTIONARY[key] || key;
    if (params) {
        Object.entries(params).forEach(([k, v]) => {
            text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
        });
    }
    return text;
};

export const translateDom = (lang?: SupportedLanguage): void => {
    const activeLang = lang || currentLanguage;
    if (typeof document === 'undefined') return;
    const docs = document.getElementById('docsFrame') as HTMLIFrameElement | null;
    if (docs) {
        const page = activeLang === 'en' ? 'documentation.html' : `documentation-${activeLang}.html`;
        docs.src = `/tools/tattoo-font-previewer/${page}`;
        docs.title = t('tab.docsFrameTitle', activeLang);
    }
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            const translated = t(key, activeLang);
            if (translated && translated !== key) {
                el.textContent = translated;
            }
        }
    });
};

